// كلمات شاذة (خارج القواعد) → جذرها
const OVERRIDES: Record<string, string> = {
  "إياك": "ايا",
  "إيانا": "ايا",
  "إيهم": "ايا",
  "أنتم": "انتم",
  "هنّ": "هن",
  "كلا": "كلا",
  "لا": "لا",
  "لم": "لم",
  "لن": "لن",
  "إن": "ان",
  "أن": "ان",
  "إذا": "اذا",
  "إذ": "اذ",
  "حتى": "حتي",
  "مع": "مع",
  "لدى": "لدي",
  "على": "علي",
  "إلى": "الي",
  "الى": "الي",
  "من": "من",
  "في": "في",
  "عن": "عن",
};

const PREFIXES = ["است", "ال", "وال", "بال", "كال", "فال", "لال", "وس", "وس", "من", "في", "عن", "إلى", "الى", "و", "ف", "ب", "ل", "ك", "س", "ي", "ت", "ا", "ن", "م"];
const SUFFIXES = ["اتها", "هما", "هم", "هن", "كم", "كن", "نا", "ون", "ين", "ات", "ان", "وا", "ها", "ته", "تم", "ت", "ن", "ه", "ك", "ي", "ا", "ة", "ى", "و"];

// تطبيع: نزع التشكيل والعلامات العلوية وتوحيد الهمزات والألفات
export function normalizeForRoot(word: string): string {
  return word
    .replace(/[\u064B-\u0652\u0670\u06D6-\u06ED\u0640\u06DD\u066D\u0660-\u0669]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[^\u0621-\u064A]/g, "")
    .trim();
}

// فهرس الجذور مرتّباً من الأطول إلى الأقصر (لتطابق الجذر الأطول أولاً)
const ROOT_KEYS = Object.keys(ROOTS).sort((a, b) => b.length - a.length);

// استخراج جذر الكلمة — heuristic محلي
export function extractRoot(rawWord: string): { root: string; meaning: string } | null {
  const w = normalizeForRoot(rawWord);
  if (w.length < 2) return null;

  // 1) الكلمة الشاذة
  const ov = OVERRIDES[rawWord.trim()] || OVERRIDES[w];
  if (ov && ROOTS[ov]) return { root: ov, meaning: ROOTS[ov] };

  // 2) توليد المرشّحات بنزع الأدوات والزوائد
  const candidates = new Set<string>([w]);
  for (const p of PREFIXES) {
    if (w.startsWith(p) && w.length - p.length >= 2) candidates.add(w.slice(p.length));
  }
  for (const s of SUFFIXES) {
    if (w.endsWith(s) && w.length - s.length >= 2) {
      const base = w.slice(0, w.length - s.length);
      candidates.add(base);
      for (const p of PREFIXES) {
        if (base.startsWith(p) && base.length - p.length >= 2) candidates.add(base.slice(p.length));
      }
    }
  }

  // 3) مطابقة الجذر الأطول (جذر مطابق تماماً أو كلمة تبدأ به)
  let best: { root: string; meaning: string } | null = null;
  for (const c of candidates) {
    if (ROOTS[c]) {
      const m = { root: c, meaning: ROOTS[c] };
      if (!best || m.root.length >= best.root.length) best = m;
      continue;
    }
    for (const r of ROOT_KEYS) {
      if (c.startsWith(r)) {
        if (!best || r.length > best.root.length) best = { root: r, meaning: ROOTS[r] };
        break; // ROOT_KEYS مرتب تنازلياً → أطول جذر يطابق أولاً
      }
    }
  }
  return best;
}

// بحث بالمعنى داخل القاموس (للاستخدام في شاشة القاموس)
export function searchRoots(query: string): RootEntry[] {
  const q = normalizeForRoot(query);
  if (!q) return [];
  return ROOT_KEYS.filter((r) => r.startsWith(q) || normalizeForRoot(ROOTS[r]).includes(q))
    .slice(0, 20)
    .map((r) => ({ root: r, meaning: ROOTS[r] }));
}

