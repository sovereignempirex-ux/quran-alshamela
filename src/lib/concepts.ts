// إيجاد المجموعة التي تنتمي إليها الكلمة (تطابق تام أو بداية)
export function findConcept(term: string): ConceptGroup | null {
  const t = term.trim();
  if (!t) return null;
  return (
    CONCEPTS.find((c) => c.terms.some((x) => x === t)) ||
    CONCEPTS.find((c) => c.terms.some((x) => x.includes(t) || t.includes(x))) ||
    null
  );
}

// كلمات التوسع الدلالي للاستعلام (بلا تكرار وبحد أقصى)
export function expandQuery(query: string): { terms: string[]; group: ConceptGroup | null } {
  const group = findConcept(query);
  if (!group) return { terms: [], group: null };
  const terms = group.terms.filter((t) => t !== query).slice(0, 4);
  return { terms, group };
}
